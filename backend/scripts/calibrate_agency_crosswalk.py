"""Calibrate the name-similarity threshold that joins USAspending's toptier
agencies to the Federal Register's agencies (fetch/agencies.crosswalk), and
write it to app/data/agency_crosswalk.json (AGENTS.md §3a).

Labels come from evidence the score never reads: an agency's abbreviation.
Where a USAspending agency's abbreviation equals the short name of exactly
one Register agency ("EPA" and "EPA"), that pair is taken as the right
match, a positive, scored by name alone. Its negative is the same agency's
best score against every *other* Register agency: the score a wrong match
gets when the right agency is missing from the Register's list, which is
exactly the case the threshold exists to refuse. The threshold maximizes
Youden's J (true-positive rate less false-positive rate) over those pairs,
placed midway between the two observed scores that bound the best interval.

Two requests, both public: the Register's agency list and USAspending's
toptier list. app/data_refresh.py reruns it monthly, into a candidate it
gates (a reorganization or a new agency moves the labels with it); the
bundled file is the fallback before the first refresh.

    python backend/scripts/calibrate_agency_crosswalk.py [OUT]
"""

import asyncio
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from app.http_client import make_async_client  # noqa: E402
from app.pipeline.fetch.agencies import (  # noqa: E402
    CROSSWALK_PATH,
    FR_AGENCIES_URL,
    TOPTIER_URL,
    crosswalk,
    fetch_fr_agencies,
    fetch_toptier_agencies,
    name_similarity,
    normalized_name,
)
from app.time_utils import utcnow  # noqa: E402


def labelled_pairs(fr: list[dict], toptier: list[dict]) -> tuple[list[float], list[float], list[dict]]:
    by_short: dict[str, list[dict]] = {}
    for a in fr:
        if a.get("short_name"):
            by_short.setdefault(a["short_name"].strip().upper(), []).append(a)
    fr_norm = [(a["slug"], normalized_name(a["name"])) for a in fr]
    positives, negatives, labels = [], [], []
    for t in toptier:
        same = by_short.get((t.get("abbreviation") or "").strip().upper(), [])
        if len(same) != 1:
            continue
        right = same[0]["slug"]
        n = normalized_name(t["agency_name"])
        scores = {slug: name_similarity(n, fn) for slug, fn in fr_norm}
        pos = scores[right]
        neg_slug, neg = max(((s, v) for s, v in scores.items() if s != right), key=lambda p: p[1])
        positives.append(pos)
        negatives.append(neg)
        labels.append({"toptierCode": t["toptier_code"], "name": t["agency_name"], "slug": right,
                       "score": round(pos, 4), "bestOther": neg_slug, "bestOtherScore": round(neg, 4)})
    return positives, negatives, labels


def youden_threshold(positives: list[float], negatives: list[float]) -> tuple[float, float]:
    """(threshold, J): the J-maximizing cut, midway into its interval."""
    scores = sorted(set(positives) | set(negatives))
    best_j, best_i = -1.0, 0
    for i, t in enumerate(scores):
        j = sum(p >= t for p in positives) / len(positives) - sum(n >= t for n in negatives) / len(negatives)
        if j > best_j:
            best_j, best_i = j, i
    upper = scores[best_i]
    lower = scores[best_i - 1] if best_i else upper
    return round((lower + upper) / 2, 4), round(best_j, 4)


async def main() -> None:
    out_path = Path(sys.argv[1]) if len(sys.argv) > 1 else CROSSWALK_PATH
    async with make_async_client() as client:
        fr = await fetch_fr_agencies(client)
        toptier = await fetch_toptier_agencies(client)
    if fr is None or toptier is None:
        raise SystemExit("A source could not be read; nothing written.")
    positives, negatives, labels = labelled_pairs(fr, toptier)
    threshold, j = youden_threshold(positives, negatives)
    matches = crosswalk({a["slug"]: a["name"] for a in fr},
                        {t["toptier_code"]: t["agency_name"] for t in toptier}, threshold)
    tp = sum(p >= threshold for p in positives)
    fp = sum(n >= threshold for n in negatives)
    out = {
        "_source": (
            "Generated by backend/scripts/calibrate_agency_crosswalk.py from the Federal Register's "
            f"agency list ({FR_AGENCIES_URL}) and USAspending's toptier agencies ({TOPTIER_URL}). "
            "Names are compared token-sorted by SequenceMatcher ratio (fetch/agencies.normalized_name). "
            "Positives: USAspending agencies whose abbreviation equals the short name of exactly one "
            "Register agency, scored against it. Negatives: the same agencies' best score against every "
            "other Register agency. threshold maximizes Youden's J over them, midway between the two "
            "observed scores bounding the best interval. matched/unmatched are what the threshold gives "
            "on these lists today, for reading; the weekly sync recomputes them."
        ),
        "_as_of": utcnow().date().isoformat(),
        "threshold": threshold,
        "youden_j": j,
        "labelled": len(positives),
        "positives_at_or_above": tp,
        "negatives_at_or_above": fp,
        "fr_agencies": len(fr),
        "toptier_agencies": len(toptier),
        "matched": len(matches),
        "unmatched": sorted(t["agency_name"] for t in toptier if t["toptier_code"] not in matches),
        "labels": sorted(labels, key=lambda r: r["score"]),
    }
    out_path.write_text(json.dumps(out, indent=1) + "\n")
    print(f"threshold {threshold} (J {j}); {tp}/{len(positives)} positives and "
          f"{fp}/{len(negatives)} negatives at or above; {len(matches)}/{len(toptier)} matched")


if __name__ == "__main__":
    asyncio.run(main())
