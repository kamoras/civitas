"""Calibrate the relevance a race-coverage item needs before Civitas posts it.

Writes app/data/race_post_relevance.json, which
analyze/election_bluesky.post_relevance_threshold reads: the stored
race_relevance cosine an item must reach to be posted as an update on its
race, the hash of the labels it was fitted to, and the held-out measurement.
Rerun when app/data/race_post_relevance_labels.json changes (the test fails
until the hash matches). Reads no database and no model: the labels carry
each item's stored relevance.

Why a second threshold. race_relevance's own threshold (Otsu, no labels)
decides what the race page shows beside its source; a post asserts the
story is about the race in Civitas's voice. On the labelled items that
name the race, the Otsu cut (0.27 on 2026-10-17) kept stories that were
about the race 65% of the time.

Method. Only the items the other checks would let through are used: those
that name the race (names_the_race; the ingest drops the rest) and whose
candidate is not known to be off the November ballot (not_on_november_ballot;
the poster refuses those). The rows are split by id, which is ingest order: the
oldest two thirds train, the newest third is held out. The threshold is the
Action Center's precision rule on the training rows: the lowest cut whose
exact (Clopper-Pearson) lower 95% bound on precision (about_race of the
items at or above it) is at least PRECISION_LOWER_BOUND, or, when none is,
the cut with the highest bound. The held-out rows are then scored at that
cut and reported, never chosen from.

Usage:
    python backend/scripts/calibrate_race_post_relevance.py
"""

from __future__ import annotations

import hashlib
import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))

from app.forecast.accountability import clopper_pearson  # noqa: E402

DATA = pathlib.Path(__file__).resolve().parent.parent / "app" / "data"
LABELS_PATH = DATA / "race_post_relevance_labels.json"
CALIBRATION_PATH = DATA / "race_post_relevance.json"
# The Action Center's precision rule (committee routing, relevance gate).
PRECISION_LOWER_BOUND = 0.8
# Oldest share of rows used to choose; the rest are held out (a convention).
TRAIN_SHARE = 2 / 3


def data_hash(rows: list[dict]) -> str:
    return hashlib.sha256(json.dumps(rows, sort_keys=True).encode()).hexdigest()[:16]


def measure(rows: list[dict], cut: float) -> dict:
    kept = [r for r in rows if r["relevance"] >= cut]
    k, n = sum(r["about_race"] for r in kept), len(kept)
    about = sum(r["about_race"] for r in rows)
    return {
        "items": len(rows),
        "about_race": about,
        "posted_at_cut": n,
        "precision": round(k / n, 3) if n else None,
        "precision_interval": clopper_pearson(k, n),
        "recall": round(k / about, 3) if about else None,
    }


def choose(rows: list[dict]) -> tuple[float, bool]:
    cuts = sorted({r["relevance"] for r in rows})
    bounds = [(cut, (measure(rows, cut)["precision_interval"] or [0.0])[0]) for cut in cuts]
    meeting = [cut for cut, lo in bounds if lo >= PRECISION_LOWER_BOUND]
    if meeting:
        return min(meeting), True
    return max(bounds, key=lambda b: (b[1], -b[0]))[0], False


def calibrate(labels: dict) -> dict:
    rows = sorted(
        (r for r in labels["rows"] if r["names_the_race"] and not r["not_on_november_ballot"]),
        key=lambda r: r["id"],
    )
    split = int(len(rows) * TRAIN_SHARE)
    train, held = rows[:split], rows[split:]
    cut, met = choose(train)
    unnamed = [r for r in labels["rows"] if not r["names_the_race"]]
    off_ballot = [r for r in labels["rows"] if r["names_the_race"] and r["not_on_november_ballot"]]
    return {
        "_source": (
            "Generated by backend/scripts/calibrate_race_post_relevance.py from "
            "app/data/race_post_relevance_labels.json. threshold is the lowest stored race_relevance "
            f"cosine whose exact (Clopper-Pearson) lower 95% bound on precision is at least {PRECISION_LOWER_BOUND} "
            f"(else the one with the highest bound), chosen on the oldest {round(TRAIN_SHARE * 100)}% of the "
            "labelled items that name their race and whose candidate is not known to be off the November "
            "ballot (by id, ingest order); held_out is the newest rest at that "
            "cut, not chosen from. precision_interval is the 95% Clopper-Pearson interval. "
            "dropped_for_not_naming_the_race is the labelled items the ingest now drops because they name "
            "neither the race's state nor another of its candidates; refused_for_a_candidate_off_the_november_"
            "ballot is the rest whose candidate the state's certified list leaves out, which the poster refuses."
        ),
        "data_hash": data_hash(labels["rows"]),
        "threshold": cut,
        "precision_rule_met_on_training": met,
        "training": measure(train, cut),
        "held_out": measure(held, cut),
        "dropped_for_not_naming_the_race": {
            "items": len(unnamed),
            "about_race": sum(r["about_race"] for r in unnamed),
            "posted": sum(r["posted"] for r in unnamed),
        },
        "refused_for_a_candidate_off_the_november_ballot": {
            "items": len(off_ballot),
            "about_race": sum(r["about_race"] for r in off_ballot),
            "posted": sum(r["posted"] for r in off_ballot),
        },
    }


def main() -> None:
    out = calibrate(json.loads(LABELS_PATH.read_text()))
    CALIBRATION_PATH.write_text(json.dumps(out, indent=1) + "\n")
    print(json.dumps(out, indent=1))


if __name__ == "__main__":
    main()
