"""Write app/data/apportionment.json: each decennial census's House
apportionment (seats per state), from the Census Bureau's own table.

The Bureau publishes each census's apportionment as Table 1 under
decennial/<year>/data/apportionment/apportionment-<year>-table01.xlsx (the
2020 census's on 2021-04-26; the 2030 census's is due by 2030-12-31, 13
U.S.C. 141(b)). Every census year from 2020 to now is looked for by that
rule, so the next one is read the day it is published, with no edit here.

Readers: the electoral votes of a presidential cycle (the apportionment the
election is held under: app/electoral_votes.py), the redrawn-maps
derivation's check of a new census's block files (every state's seat count
in the block file is its apportionment's), and the district tables' seat
gates.

Gates (any failure writes nothing): every census holds the 50 states, each
with at least one seat, summing to the House's 435 (2 U.S.C. 2a); and the
newest census on file before is still found (a census once published is
never lost from the file).

Usage: fetch_apportionment.py OUT
"""

from __future__ import annotations

import argparse
import datetime as dt
import io
import json
import re
import sys
import urllib.error
import xml.etree.ElementTree as ET
import zipfile
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(BACKEND))
from app import census_lines  # noqa: E402
from app.state_names import STATE_NAME_TO_CODE  # noqa: E402

FIRST_CENSUS = 2020  # the first census this site's district data are drawn on
URL = ("https://www2.census.gov/programs-surveys/decennial/{year}/data/apportionment/"
       "apportionment-{year}-table01.xlsx")
HOUSE_SEATS = 435  # 2 U.S.C. 2a
_NS = {"s": "http://schemas.openxmlformats.org/spreadsheetml/2006/main"}


def sheet_rows(xlsx: bytes) -> list[list[str]]:
    """The first sheet's cells as text, row by row (shared strings resolved)."""
    with zipfile.ZipFile(io.BytesIO(xlsx)) as zf:
        shared = []
        if "xl/sharedStrings.xml" in zf.namelist():
            for si in ET.fromstring(zf.read("xl/sharedStrings.xml")).findall("s:si", _NS):
                shared.append("".join(t.text or "" for t in si.iter(f"{{{_NS['s']}}}t")))
        sheet = ET.fromstring(zf.read("xl/worksheets/sheet1.xml"))
    rows = []
    for row in sheet.iter(f"{{{_NS['s']}}}row"):
        cells = []
        for c in row.findall("s:c", _NS):
            v = c.find("s:v", _NS)
            text = "" if v is None else v.text or ""
            cells.append(shared[int(text)] if c.get("t") == "s" and text else text)
        rows.append(cells)
    return rows


def seats_from_table(rows: list[list[str]]) -> dict[str, int]:
    """{state: seats} from Table 1: each state's row holds its name and,
    after its apportionment population, its number of representatives."""
    out = {}
    for cells in rows:
        if not cells or cells[0].strip() not in STATE_NAME_TO_CODE:
            continue
        numbers = [c for c in cells[1:] if re.fullmatch(r"-?\d+(\.0+)?", c.strip())]
        if len(numbers) >= 2:
            out[STATE_NAME_TO_CODE[cells[0].strip()]] = int(float(numbers[1]))
    return {st: n for st, n in out.items() if st != "DC"}


def gate(censuses: dict[str, dict[str, int]], before: dict) -> list[str]:
    failures = []
    for year, seats in censuses.items():
        if len(seats) != 50 or min(seats.values(), default=0) < 1 or sum(seats.values()) != HOUSE_SEATS:
            failures.append(f"{year}: {len(seats)} states, {sum(seats.values())} seats")
    lost = sorted(set(before.get("censuses") or {}) - set(censuses))
    if lost:
        failures.append(f"censuses on file before and not found now: {lost}")
    return failures


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("out", type=Path)
    args = ap.parse_args(argv)
    censuses, sources = {}, {}
    for year in range(FIRST_CENSUS, dt.date.today().year + 1, 10):
        url = URL.format(year=year)
        try:
            payload = census_lines._get(url)
        except urllib.error.HTTPError as exc:
            if exc.code == 404:
                continue  # not published yet
            raise
        censuses[str(year)] = seats_from_table(sheet_rows(payload))
        sources[str(year)] = url
    before = census_lines.bundled_json("apportionment.json")
    failures = gate(censuses, before)
    if failures:
        print("REFUSING TO WRITE:", "; ".join(failures))
        return 1
    args.out.write_text(json.dumps({
        "_source": ("U.S. Census Bureau, Table 1 (apportionment population and number of representatives by "
                    "state) of each decennial census: " + "; ".join(f"{y}: {u}" for y, u in sources.items())
                    + ". Generated by backend/scripts/fetch_apportionment.py."),
        "censuses": censuses,
    }, indent=1) + "\n")
    print(f"wrote {args.out}: {', '.join(censuses)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
