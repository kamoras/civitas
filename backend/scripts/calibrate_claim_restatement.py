"""Calibrate claims.distinct_claims's restatement threshold.

Writes app/data/claim_restatement_calibration.json: the similarity-model
cosine at or above which two claims are one fact restated, the hash of the
labelled pairs it was fitted to (app/data/claim_restatement_pairs.json), and
the measurement. Rerun when the pairs change, or when the similarity model
does (tests/test_claims.py fails until the hash matches).

Method. Each labelled pair's cosine (all-MiniLM-L6-v2, unit vectors). The
threshold is the lowest on the grid whose precision — the share of pairs at
or above it that are labelled restatements — has a lower 95% bootstrap
bound of at least PRECISION_LOWER_BOUND: a false call drops a real second
fact, and an issue needs two. Token overlap (the share of the shorter
claim's words in the longer, dedupe_claims's measure generalised) is
reported beside it as the alternative it was measured against.

Usage (loads all-MiniLM-L6-v2; no network once the model is cached):
    python backend/scripts/calibrate_claim_restatement.py
"""

from __future__ import annotations

import datetime
import json
import pathlib
import sys

import numpy as np

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from app.pipeline import vector_store  # noqa: E402
from app.pipeline.analyze.claims import (  # noqa: E402
    RESTATEMENT_CALIBRATION_PATH,
    _tokens,
    restatement_pairs,
    restatement_pairs_hash,
)

THRESHOLD_GRID = np.round(np.arange(0.40, 0.951, 0.05), 2)
BOOTSTRAP = 4000
# A bar on the precision's lower 95% bound, not its point estimate (as
# calibrate_committee_routing.py's 0.80), and a fixed policy, not a fitted
# value. Higher than routing's because the errors are lopsided: a missed
# restatement leaves an issue as it was before this check existed, while a
# false one drops a real second fact and, under the two-claim gate, the
# issue. At 0.80 the threshold came out 0.70, and on the replay of
# 2026-10-11..15 that called "$10 million spent" and "nearly $22 million
# spent" one fact and dropped a published story; at 0.85 it is 0.75, which
# keeps it and still catches every restatement that replay held.
PRECISION_LOWER_BOUND = 0.85


def auc(scores: np.ndarray, truth: np.ndarray) -> float:
    pos, neg = scores[truth], scores[~truth]
    wins = (pos[:, None] > neg[None, :]).sum() + 0.5 * (pos[:, None] == neg[None, :]).sum()
    return float(wins / max(len(pos) * len(neg), 1))


def precision_recall(truth: np.ndarray, flagged: np.ndarray) -> tuple[float, float]:
    tp = float(np.sum(truth & flagged))
    return tp / max(flagged.sum(), 1), tp / max(truth.sum(), 1)


def interval(truth: np.ndarray, scores: np.ndarray, threshold: float) -> dict:
    rng = np.random.default_rng(0)
    draws = []
    for _ in range(BOOTSTRAP):
        i = rng.integers(0, len(truth), len(truth))
        draws.append(precision_recall(truth[i], scores[i] >= threshold))
    lo, hi = np.percentile(np.array(draws), [2.5, 97.5], axis=0)
    p, r = precision_recall(truth, scores >= threshold)
    return {
        "threshold": threshold,
        "flagged": int(np.sum(scores >= threshold)),
        "precision": [round(p, 3), round(lo[0], 3), round(hi[0], 3)],
        "recall": [round(r, 3), round(lo[1], 3), round(hi[1], 3)],
    }


def main() -> None:
    pairs = restatement_pairs()
    truth = np.array([p["restatement"] for p in pairs])
    texts = sorted({t for p in pairs for t in (p["a"], p["b"])})
    vectors = vector_store.encode_normalized(vector_store.get_similarity_model(), texts)
    row = {t: i for i, t in enumerate(texts)}
    cosine = np.array([float(vectors[row[p["a"]]] @ vectors[row[p["b"]]]) for p in pairs])

    def overlap(a: str, b: str) -> float:
        x, y = _tokens(a), _tokens(b)
        return len(x & y) / max(1, min(len(x), len(y)))

    token_overlap = np.array([overlap(p["a"], p["b"]) for p in pairs])

    grid = {float(t): interval(truth, cosine, float(t)) for t in THRESHOLD_GRID}
    meeting = [t for t, m in grid.items() if m["flagged"] and m["precision"][1] >= PRECISION_LOWER_BOUND]
    if not meeting:
        raise SystemExit("No threshold meets the precision bar; leave the gate as it is.")
    threshold = min(meeting)
    overlap_meeting = [
        float(t) for t in THRESHOLD_GRID
        if interval(truth, token_overlap, float(t))["precision"][1] >= PRECISION_LOWER_BOUND
    ]
    out = {
        "_source": (
            "Generated by backend/scripts/calibrate_claim_restatement.py from "
            "app/data/claim_restatement_pairs.json: the similarity-model (all-MiniLM-L6-v2) "
            "cosine at or above which claims.distinct_claims treats two claims as one fact. "
            "The lowest threshold whose precision has a lower 95% bootstrap bound of at least "
            f"{PRECISION_LOWER_BOUND}. Figures are [value, 2.5%, 97.5%]."
        ),
        "_as_of": datetime.date.today().isoformat(),
        "pairs_hash": restatement_pairs_hash(),
        "pairs": len(pairs),
        "restatements": int(truth.sum()),
        "threshold": threshold,
        "cosine_auc": round(auc(cosine, truth), 3),
        "chosen": grid[threshold],
        "token_overlap_auc": round(auc(token_overlap, truth), 3),
        "token_overlap_at_its_own_bar": (
            interval(truth, token_overlap, min(overlap_meeting)) if overlap_meeting else None
        ),
    }
    RESTATEMENT_CALIBRATION_PATH.write_text(json.dumps(out, indent=1) + "\n")
    print(json.dumps(out, indent=1))


if __name__ == "__main__":
    main()
