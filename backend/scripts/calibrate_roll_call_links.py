"""Fit the threshold for linking news stories to roll calls (app/roll_call_links.py).

Reads the hand-labelled pairs in app/data/roll_call_link_examples.json: each
item is a dated story (an Action Center issue, a monitor update, a timeline
entry) with every roll call in its window (`candidates`) and the ones a
reader of the story would take as a vote on what it covers (`related`).
Writes app/data/roll_call_link_calibration.json:

  - the threshold: over every labelled pair, the one where the precision's
    exact (Clopper-Pearson) lower 95% bound is highest, when that bound is
    at least PRECISION_LOWER_BOUND (choose), or null when it isn't (then
    nothing is linked);
  - held_out: the same rule run FOLDS times, each time choosing the
    threshold on all but one block of consecutive dates and scoring that
    block (a block whose training folds meet the bound nowhere is scored
    at their best bound), pooled; with precision's exact bound and recall,
    and the issues among them alone. That is the number to quote: no pair
    is scored at a threshold chosen with its own label.

Run from backend/ (needs both sentence-transformer models):
    python -m scripts.calibrate_roll_call_links
"""

from __future__ import annotations

import json

import numpy as np
from scipy.stats import beta

from app import roll_call_links as rcl
from app.time_utils import utcnow

# The Action Center's bar for anything shown as fact.
PRECISION_LOWER_BOUND = 0.80
FOLDS = 4
GRID = [round(float(t), 3) for t in np.arange(0.30, 0.901, 0.005)]


def exact_lower(correct: int, named: int) -> float:
    return float(beta.ppf(0.025, correct, named - correct + 1)) if correct else 0.0


def summary(named: np.ndarray, y: np.ndarray) -> dict:
    k, n, p = int((named & y).sum()), int(named.sum()), int(y.sum())
    return {
        "named": n, "correct": k, "positives": p,
        "precision": round(k / n, 3) if n else None,
        "precision_exact_lower": round(exact_lower(k, n), 3),
        "recall": round(k / p, 3) if p else None,
    }


def choose(sc: np.ndarray, y: np.ndarray) -> tuple[float | None, float]:
    """(threshold, the threshold with the best bound). The threshold is the
    one whose precision's exact lower bound is highest (the lowest such on a
    tie), or None when even that misses PRECISION_LOWER_BOUND. Taking
    instead the lowest threshold whose bound reached the bar put it at the
    curve's edge: chosen that way on three blocks of dates, the fourth held
    out at a bound of 0.78 to 0.80 depending on the blocks, under the bar.
    At the peak it held out at 0.88."""
    curve = [(t, summary(sc >= t, y)["precision_exact_lower"]) for t in GRID]
    best_t, best_b = max(curve, key=lambda c: (c[1], -c[0]))
    return (best_t if best_b >= PRECISION_LOWER_BOUND else None), best_t


def main() -> None:
    ex = rcl.examples()
    items, votes = ex["items"], ex["roll_calls"]
    refs = sorted(votes)
    col = {r: c for c, r in enumerate(refs)}
    encode = rcl.encoders()
    story_texts = [rcl.story_text(i["title"]) for i in items]
    vote_texts = [rcl.roll_call_text(votes[r]["question"], votes[r]["title"], votes[r].get("purpose")) for r in refs]
    sv = {m: encode[m](story_texts) for m in rcl.MODELS}
    vv = {m: encode[m](vote_texts) for m in rcl.MODELS}
    full = rcl.scores(sv, vv)

    rows = [(i, col[r], r in item["related"], item["date"], item["kind"])
            for i, item in enumerate(items) for r in item["candidates"] if rcl.linkable(votes[r]["question"], votes[r].get("purpose"))]
    sc = np.array([full[i, c] for i, c, *_ in rows])
    y = np.array([lab for _, _, lab, _, _ in rows])
    days = np.array([d for *_, d, _ in rows])
    issues = np.array([k == "issue" for *_, k in rows])

    threshold, best = choose(sc, y)
    at = threshold if threshold is not None else best

    # Blocks of consecutive dates, each holding about 1/FOLDS of the positives.
    pos_days = sorted(days[y])
    edges = np.array([pos_days[int(len(pos_days) * f / FOLDS)] for f in range(1, FOLDS)])
    fold = np.searchsorted(edges, days, side="right")
    named = np.zeros(len(sc), bool)
    folds = []
    for f in range(FOLDS):
        test = fold == f
        t_meet, t_best = choose(sc[~test], y[~test])
        t = t_meet if t_meet is not None else t_best
        named[test] = sc[test] >= t
        folds.append({"from": min(days[test]), "to": max(days[test]), "threshold": t,
                      "threshold_met_bound": t_meet is not None, **summary(named[test], y[test])})

    out = {
        "_source": (
            "Generated by backend/scripts/calibrate_roll_call_links.py from "
            "app/data/roll_call_link_examples.json (the headline against the vote's title, scored as the "
            "mean of the all-MiniLM-L6-v2 and Snowflake Arctic-XS cosines; an amendment vote embedded as its stated "
            "purpose, and left out without one, roll_call_links.linkable). threshold is, over every "
            "labelled pair, the one where the precision's exact (Clopper-Pearson) lower 95% bound is "
            f"highest, when that bound is at least {PRECISION_LOWER_BOUND}, else null (nothing is then "
            "linked); all_pairs and all_issues "
            f"score it. held_out runs the same choice {FOLDS} times, each on all but one block of "
            "consecutive dates, scoring the block left out, pooled (held_out_issues: the issues among "
            "them); folds lists each block."
        ),
        "_as_of": str(utcnow().date()),
        "data_hash": rcl.data_hash(),
        "window_days": list(rcl.WINDOW),
        "pairs": len(rows), "positive_pairs": int(y.sum()),
        "threshold": threshold,
        "precision_rule_met": threshold is not None,
        "all_pairs": {"threshold": at, **summary(sc >= at, y)},
        "all_issues": {"threshold": at, **summary((sc >= at)[issues], y[issues])},
        "held_out": summary(named, y),
        "held_out_issues": summary(named[issues], y[issues]),
        "folds": folds,
        "curve": [{"threshold": t, **summary(sc >= t, y)} for t in GRID],
    }
    rcl.CALIBRATION_PATH.write_text(json.dumps(out, indent=1) + "\n")
    for k in ("threshold", "all_pairs", "all_issues", "held_out", "held_out_issues", "folds"):
        print(k, out[k])


if __name__ == "__main__":
    main()
