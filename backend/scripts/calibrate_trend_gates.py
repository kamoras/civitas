"""Calibrate the trend-post gates (app/pipeline/analyze/trend_relevance.py).

Writes app/data/trend_gates_calibration.json: for each gate, k, the vote
threshold, the hash of the labelled set it was fitted to, and the
leave-one-out measurement. Rerun when an examples file changes, or when the
similarity model does (test_trend_gates_calibration_matches_examples fails
until the hashes match).

Method. Leave-one-out: each example is scored by its k nearest OTHER
examples, with near-duplicates of it (cosine > 0.95, the same topic trending
twice) dropped too, so a repeat can't vote for itself. k is the grid value
with the best leave-one-out AUC. Each threshold is chosen for what its
mistake costs:

  - relevance: 0.5, a decision (the trend-post design), not a fit; the
    measurement at it is reported.
  - tragedy: the highest threshold that still flags 90% of labelled
    tragedies. A missed tragedy goes down the ordinary path, which needs an
    official record anyway; a false flag only demands more of a record.
  - political_violence: the lowest threshold with 90% precision: a tragedy
    posted on a weak political reading is the costly mistake.
  - loaded: the threshold with the best F2 (recall weighted twice
    precision): quoting a loaded name is the costlier mistake, a false flag
    only skips one trend. A recall target was tried first and rejected:
    the vote reads topic as much as framing, so 90% recall flagged a third
    of plainly named topics (precision 0.34 at threshold 0.2 against 0.53
    at the F2 point, 2026-10-15).

AUC and the chosen point's precision/recall carry 95% bootstrap intervals.

Usage (loads all-MiniLM-L6-v2; no network once the model is cached):
    python backend/scripts/calibrate_trend_gates.py
"""

from __future__ import annotations

import datetime
import json
import pathlib
import sys

import numpy as np

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from app.pipeline.analyze.action_center import _embed_texts_sim  # noqa: E402
from app.pipeline.analyze.trend_relevance import (  # noqa: E402
    CALIBRATION_PATH,
    GATES,
    gate_examples,
    gate_examples_hash,
)

K_GRID = (5, 9, 15, 25)
THRESHOLDS = np.round(np.arange(0.05, 0.951, 0.05), 2)
NEAR_DUPLICATE = 0.95
TARGET = 0.90
RELEVANCE_THRESHOLD = 0.5
BOOTSTRAP = 2000


def loo_votes(sims: np.ndarray, labels: np.ndarray, k: int) -> np.ndarray:
    out = np.empty(len(labels))
    for i in range(len(labels)):
        s = sims[i].copy()
        s[i] = -9
        s[sims[i] > NEAR_DUPLICATE] = -9
        nearest = np.argsort(-s)[:k]
        w = s[nearest].clip(min=0)
        out[i] = (w * labels[nearest]).sum() / max(w.sum(), 1e-9)
    return out


def auc(scores: np.ndarray, labels: np.ndarray) -> float:
    p, n = scores[labels == 1], scores[labels == 0]
    return float((p[:, None] > n[None, :]).mean() + 0.5 * (p[:, None] == n[None, :]).mean())


def pr(scores: np.ndarray, labels: np.ndarray, t: float) -> tuple[float, float]:
    kept = scores >= t
    tp = float((kept & (labels == 1)).sum())
    return tp / max(kept.sum(), 1), tp / max((labels == 1).sum(), 1)


def interval(fn, scores: np.ndarray, labels: np.ndarray) -> list[float]:
    rng = np.random.default_rng(0)
    draws = []
    for _ in range(BOOTSTRAP):
        i = rng.integers(0, len(labels), len(labels))
        if labels[i].min() == labels[i].max():
            continue
        draws.append(fn(scores[i], labels[i]))
    lo, hi = np.percentile(draws, [2.5, 97.5])
    return [round(fn(scores, labels), 3), round(float(lo), 3), round(float(hi), 3)]


def choose(gate: str, scores: np.ndarray, labels: np.ndarray) -> float:
    if gate == "relevance":
        return RELEVANCE_THRESHOLD
    if gate == "political_violence":
        ok = [t for t in THRESHOLDS if pr(scores, labels, t)[0] >= TARGET]
        return float(min(ok)) if ok else float(THRESHOLDS[-1])
    if gate == "loaded":
        def f2(t: float) -> float:
            p, r = pr(scores, labels, t)
            return 5 * p * r / max(4 * p + r, 1e-12)
        return float(max(THRESHOLDS, key=f2))
    ok = [t for t in THRESHOLDS if pr(scores, labels, t)[1] >= TARGET]
    return float(max(ok)) if ok else float(THRESHOLDS[0])


def main() -> None:
    out = {
        "_source": (
            "Generated by backend/scripts/calibrate_trend_gates.py from the labelled sets named per gate: "
            "k (best leave-one-out AUC over K_GRID, near-duplicates excluded) and the vote threshold for each "
            "similarity-weighted kNN vote (all-MiniLM-L6-v2), chosen per the script's docstring. Intervals are "
            "[value, 2.5%, 97.5%] bootstrap."
        ),
        "_as_of": datetime.date.today().isoformat(),
        "_why_relevance_threshold": "0.5 is the trend-post design's decision; the measurement at it is reported.",
    }
    for gate, (path, label, subset) in GATES.items():
        examples = gate_examples(gate)
        labels = np.array([bool(e[label]) for e in examples], dtype=float)
        emb = _embed_texts_sim([e["text"] for e in examples])
        sims = emb @ emb.T
        by_k = {k: loo_votes(sims, labels, k) for k in K_GRID}
        k = max(K_GRID, key=lambda kk: auc(by_k[kk], labels))
        scores = by_k[k]
        t = choose(gate, scores, labels)
        out[gate] = {
            "examples_file": path.name,
            "label": label,
            "subset": subset,
            "examples_hash": gate_examples_hash(gate),
            "examples": len(examples),
            "positives": int(labels.sum()),
            "k": k,
            "threshold": t,
            "loo_auc": interval(auc, scores, labels),
            "auc_by_k": {str(kk): round(auc(v, labels), 3) for kk, v in by_k.items()},
            "precision": interval(lambda s, y: pr(s, y, t)[0], scores, labels),
            "recall": interval(lambda s, y: pr(s, y, t)[1], scores, labels),
        }
        print(gate, out[gate]["k"], t, out[gate]["loo_auc"], out[gate]["precision"], out[gate]["recall"])
    CALIBRATION_PATH.write_text(json.dumps(out, indent=1) + "\n")


if __name__ == "__main__":
    main()
