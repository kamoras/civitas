"""Bundle post_composer's actor threshold for a database with no refit yet.

Writes app/data/claim_actor_threshold.json: the threshold
post_composer.fit_actor_threshold sets on the claim calls recorded in the
database DATABASE_URL points at (a production snapshot), the same fit the
Action Center refresh runs once a day (refit_actor_threshold). Nothing is
labelled by hand: the non-actors are the calls' own predicates and the sums
and percentages in their sources (post_composer's comment above
ACTOR_PROTOTYPES). Rerun when ACTOR_PROTOTYPES or NON_ACTOR_PROTOTYPES
change, or when the similarity model does.

Usage (loads all-MiniLM-L6-v2; no network once the model is cached):
    DATABASE_URL=sqlite:////path/to/snapshot.db python backend/scripts/calibrate_claim_actor.py
"""

from __future__ import annotations

import datetime
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from app.database import SessionLocal  # noqa: E402
from app.models import LlmGenerationSample  # noqa: E402
from app.pipeline.analyze.post_composer import (  # noqa: E402
    _REFIT_CALLS,
    ACTOR_THRESHOLD_PATH,
    CLAIM_TASK,
    actor_negatives,
    fit_actor_threshold,
)


def main() -> None:
    with SessionLocal() as db:
        calls = (db.query(LlmGenerationSample.input_text, LlmGenerationSample.output_json)
                 .filter(LlmGenerationSample.task == CLAIM_TASK)
                 .order_by(LlmGenerationSample.id.desc()).limit(_REFIT_CALLS).all())
    negatives = actor_negatives([(c.input_text, c.output_json) for c in calls])
    threshold = fit_actor_threshold(negatives)
    if threshold is None:
        sys.exit(f"only {len(negatives)} non-actors in {len(calls)} claim calls; not enough to fit")
    out = {
        "_source": (
            "Generated by backend/scripts/calibrate_claim_actor.py: the lowest prototype margin "
            "(post_composer.actor_margins, all-MiniLM-L6-v2) that no data-supplied non-actor reaches, over "
            f"the {len(calls)} newest recorded claim calls of a production snapshot: their predicates and "
            "the sums and percentages in their sources, among spans the capitalised-word rule refuses. "
            "Used only until the Action Center refresh's daily refit (post_composer.refit_actor_threshold) "
            "has stored one."
        ),
        "_as_of": datetime.date.today().isoformat(),
        "threshold": threshold,
        "calls": len(calls),
        "negatives": len(negatives),
    }
    ACTOR_THRESHOLD_PATH.write_text(json.dumps(out, indent=2) + "\n")
    print(json.dumps(out, indent=2))


if __name__ == "__main__":
    main()
