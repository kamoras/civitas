"""Fit the bill classifier's procedural-seed threshold on the Congressional
Research Service's own policy areas, and write it to
app/data/procedural_calibration.json (AGENTS.md §3a).

bill_analyzer._is_procedural_seed_match calls a bill PROCEDURAL (ceremonial
or administrative: naming a post office, a commemorative week, a tribute)
when its title's cosine to the procedural prototype reaches the threshold,
and a PROCEDURAL bill leaves the policy analysis. Labels come from the
policy area CRS assigns every bill (Congress.gov's `policyArea`, read from
the sponsored-legislation lists the pipeline caches): "Commemorations" is
procedural; a bill in an area that names a policy subject (the areas
app/data/crs_policy_areas.json maps to a taxonomy category other than
PROCEDURAL) is not. Areas that mix the two ("Congress": house rules beside
ethics and stock-trading bills; "Government Operations and Politics") and
bills with no area are left out.

Threshold: the Action Center's precision rule (app/precision_rule.py): the
grid point whose precision's exact lower 95% bound is highest, used only
when that bound is at least 0.80, else null and the seed check never fires
(the kNN and prototype tiers classify every bill). Fitted on half the
labels (split by a hash of the title), measured on the other half.

Usage (loads the classification model; no network once it is cached):
    DATABASE_URL=sqlite:////path/to/snapshot.db python backend/scripts/calibrate_procedural.py [--dry-run]
"""

from __future__ import annotations

import argparse
import hashlib
import json
import pathlib
import sys

import numpy as np
from sqlalchemy import text

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from app.database import SessionLocal  # noqa: E402
from app.pipeline.analyze import bill_analyzer as ba  # noqa: E402
from app.pipeline.vector_store import encode_normalized, get_embedding_model  # noqa: E402
from app.precision_rule import PRECISION_LOWER_BOUND, choose, summary  # noqa: E402
from app.time_utils import utcnow  # noqa: E402

GRID = [round(float(t), 2) for t in np.arange(0.50, 0.961, 0.01)]


def _h(s: str) -> int:
    return int(hashlib.sha256(s.encode()).hexdigest()[:12], 16)


def bills(db) -> dict[str, str]:
    """title -> CRS policy area, over every sponsored bill cached."""
    out: dict[str, str] = {}
    for (data,) in db.execute(text(
            "SELECT data_json FROM api_cache WHERE tier = 'congress' AND cache_key LIKE 'member-sponsored%'")):
        try:
            rows = json.loads(data)
        except ValueError:
            continue
        for b in rows if isinstance(rows, list) else []:
            area = ((b or {}).get("policyArea") or {}).get("name") if isinstance(b, dict) else None
            if area and b.get("title"):
                out.setdefault(b["title"], area)
    return out


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()
    areas = ba.crs_policy_areas()
    with SessionLocal() as db:
        titled = bills(db)
    # Every labelled title, so precision is measured at the share of
    # procedural bills the classifier actually meets (a sample balanced by
    # label would overstate it).
    positives = sorted(t for t, a in titled.items() if areas.get(a) == ["PROCEDURAL"])
    negatives = sorted(t for t, a in titled.items() if areas.get(a) and "PROCEDURAL" not in areas[a])
    texts = positives + negatives
    truth = np.array([True] * len(positives) + [False] * len(negatives))
    model = get_embedding_model()
    proto = encode_normalized(model, [ba._PROCEDURAL_PROTOTYPE])[0]
    scores = encode_normalized(model, [t[:300] for t in texts]) @ proto
    held = np.array([_h("half:" + t) % 2 == 1 for t in texts])
    threshold, best = choose(scores[~held], truth[~held], GRID)
    at = threshold if threshold is not None else best
    labels = sorted([t, bool(y)] for t, y in zip(texts, truth))
    out = {
        "_source": (
            "Generated by backend/scripts/calibrate_procedural.py from the Congressional Research Service's policy "
            "areas on the cached sponsored-legislation lists of a production snapshot: Commemorations is procedural, "
            "an area app/data/crs_policy_areas.json maps to another category is not, mixed areas left out. "
            "threshold: the grid point whose precision's exact lower 95% bound is highest on half the labels "
            f"(split by a hash of the title), used only when that bound is at least {PRECISION_LOWER_BOUND}, else "
            "null (the seed check never fires); held_out scores the other half."
        ),
        "_as_of": utcnow().date().isoformat(),
        "threshold": threshold,
        "best_bound_threshold": best,
        "labels": {"procedural": len(positives), "not_procedural": len(negatives), "bills_read": len(titled)},
        "fit_half": summary(scores[~held] >= at, truth[~held]),
        "held_out": summary(scores[held] >= at, truth[held]),
        "held_out_recall": round(float(((scores[held] >= at) & truth[held]).sum() / max(truth[held].sum(), 1)), 3),
        "labels_sha256": hashlib.sha256(json.dumps(labels).encode()).hexdigest(),
        "crs_policy_areas_sha256": hashlib.sha256(ba.CRS_POLICY_AREAS_PATH.read_bytes()).hexdigest(),
    }
    print(json.dumps(out, indent=1))
    if not args.dry_run:
        ba.PROCEDURAL_CALIBRATION_PATH.write_text(json.dumps(out, indent=1) + "\n")


if __name__ == "__main__":
    main()
