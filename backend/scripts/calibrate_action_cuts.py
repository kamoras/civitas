"""Bundle the Action Center's clustering and restatement cuts for a
database with no refit yet.

Writes app/data/cluster_pair_calibration.json and
app/data/claim_restatement_calibration.json: the cuts action_center.refit_cuts
fits once a day (fit_cluster_cut, fit_restatement_cut), fitted here on the
database DATABASE_URL points at (a production snapshot): its stored
national-feed articles (feed_articles), its published issues (whose
sources are the clustering fit's one-event pairs) and its recorded claim
calls (llm_generation_samples: each claim with its actor). Nothing
is labelled by hand. A database that does not yet hold four weeks of
feed_articles can be given the articles as a JSON list of {"title",
"description", "published"} with --articles. Rerun when the fit changes,
or when either embedding model does.

Usage (loads both embedding models; no network once they are cached):
    DATABASE_URL=sqlite:////path/to/snapshot.db python backend/scripts/calibrate_action_cuts.py [--articles FILE]
"""

from __future__ import annotations

import argparse
import datetime
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from app.database import SessionLocal  # noqa: E402
from app.models import ActionIssue, FeedArticle  # noqa: E402
from app.pipeline.analyze.action_center import (  # noqa: E402
    _CLUSTER_CALIBRATION_PATH,
    RESTATEMENT_REFIT_DAYS,
    fit_cluster_cut,
    fit_restatement_cut,
)
from app.pipeline.analyze.claims import RESTATEMENT_CALIBRATION_PATH, recorded_claims  # noqa: E402


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--articles", type=pathlib.Path)
    args = parser.parse_args()
    today = datetime.date.today().isoformat()
    with SessionLocal() as db:
        if args.articles:
            rows = json.loads(args.articles.read_text())
            articles = [(r["title"], r["description"] or "",
                         datetime.datetime.fromisoformat(r["published"].replace("Z", "+00:00")).replace(tzinfo=None),
                         r.get("url"))
                        for r in rows]
            article_source = f"the {len(articles)} national-feed articles in {args.articles.name}"
        else:
            articles = [(r.title, r.description, r.published or r.seen_at, r.url)
                        for r in db.query(FeedArticle).filter(FeedArticle.kept.is_(True))]
            article_source = f"the {len(articles)} kept national-feed articles in feed_articles"
        issue_sources = [json.loads(r.source_urls or "[]")
                         for r in db.query(ActionIssue.source_urls).filter(ActionIssue.source_type.is_(None))]
        since = (datetime.date.today() - datetime.timedelta(days=RESTATEMENT_REFIT_DAYS)).isoformat()
        issues = db.query(ActionIssue).filter(ActionIssue.source_type.is_(None), ActionIssue.date >= since).all()
        cluster = fit_cluster_cut(articles, issue_sources)
        claims = recorded_claims(db, datetime.datetime.combine(
            datetime.date.today() - datetime.timedelta(days=RESTATEMENT_REFIT_DAYS), datetime.time()))
        restatement = fit_restatement_cut(issues, [a[:3] for a in articles], claims=claims)
    if cluster is None or restatement is None:
        sys.exit(f"too few labelled pairs (cluster {cluster}, restatement {restatement})")
    cluster.update({
        "_source": ("Generated by backend/scripts/calibrate_action_cuts.py: action_center.fit_cluster_cut on "
                    f"{article_source} of a production snapshot. Used only until the Action Center refresh's "
                    "daily refit (refit_cuts) has stored one."),
        "_as_of": today,
    })
    restatement.update({
        "_source": ("Generated by backend/scripts/calibrate_action_cuts.py: action_center.fit_restatement_cut on "
                    f"the {len(issues)} news issues published in the last {RESTATEMENT_REFIT_DAYS} days, the {len(claims)} claims "
                    f"its recorded claim calls verified (llm_generation_samples) and {article_source} of a production "
                    "snapshot. Used only until the "
                    "Action Center refresh's daily refit (refit_cuts) has stored one."),
        "_as_of": today,
    })
    for path, doc in ((_CLUSTER_CALIBRATION_PATH, cluster), (RESTATEMENT_CALIBRATION_PATH, restatement)):
        path.write_text(json.dumps(doc, indent=2, sort_keys=True) + "\n")
        print(path.name, json.dumps(doc, indent=2))


if __name__ == "__main__":
    main()
