def _client(routes: dict):
    """An httpx client answering each URL from `routes` (a status, or JSON)."""
    def handle(request):
        answer = routes.get(str(request.url).split("?")[0])
        if answer is None or isinstance(answer, int):
            return httpx.Response(answer or 503)
        return httpx.Response(200, json=answer)
    return httpx.AsyncClient(transport=httpx.MockTransport(handle))


