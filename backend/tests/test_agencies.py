class TestCrosswalk:
    def test_the_registers_inverted_department_names_match(self):
        got = ag.crosswalk({"agriculture-department": "Agriculture Department"},
                           {"012": "Department of Agriculture"}, 0.83)
        assert got["012"][0] == "agriculture-department"

    def test_a_name_short_of_the_threshold_is_unmatched_not_guessed(self):
        fr = {"northern-border-regional-commission": "Northern Border Regional Commission"}
        assert ag.crosswalk(fr, {"x": "Southwest Border Regional Commission"}, 0.83) == {}

    def test_an_agency_whose_best_match_is_taken_stays_unmatched(self):
        fr = {"a": "Federal Trade Commission"}
        got = ag.crosswalk(fr, {"1": "Federal Trade Commission", "2": "Federal Trade Commissions"}, 0.5)
        assert got == {"1": ("a", 1.0)}

    def test_the_calibrated_threshold_is_generated_data(self):
        cal = ag.crosswalk_calibration()
        assert cal["_source"].startswith("Generated by backend/scripts/calibrate_agency_crosswalk.py")
        assert 0.5 < cal["threshold"] < 1


