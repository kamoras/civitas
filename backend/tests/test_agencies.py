class TestSync:
    async def test_both_sources_stored_and_crosswalked(self, db_session, quiet_alerts):
        async with _client({ag.FR_AGENCIES_URL: FR_LIST, ag.TOPTIER_URL: TOPTIER, **_budget_urls(YEARS)}) as c:
            stats = await ag.sync_agencies(db_session, c)
        assert stats["frAgencies"] == 3 and stats["matched"] == 2
        assert db_session.get(Agency, "food-and-drug-administration").parent_slug == "health-and-human-services-department"
        assert db_session.get(AgencyBudget, "075").agency_slug == "health-and-human-services-department"
        assert db_session.get(AgencyBudget, "999").agency_slug is None
        years = json.loads(db_session.get(AgencyBudget, "068").by_year)
        assert years == [{"fiscalYear": 2026, "budgetaryResources": 5.0e10, "obligated": 2.0e10,
                          "outlays": 1.0e10, "throughPeriod": 11}]
        assert quiet_alerts == []

    async def test_an_outage_leaves_what_is_stored(self, db_session, quiet_alerts):
        async with _client({ag.FR_AGENCIES_URL: FR_LIST, ag.TOPTIER_URL: TOPTIER, **_budget_urls(YEARS)}) as c:
            await ag.sync_agencies(db_session, c)
        async with _client({ag.FR_AGENCIES_URL: 500, ag.TOPTIER_URL: TOPTIER, **_budget_urls(503)}) as c:
            stats = await ag.sync_agencies(db_session, c)
        assert stats["frAgencies"] is None and stats["byYearFailed"] == 3
        assert db_session.query(Agency).count() == 3
        # The year-by-year figures read last week stay; the matches too.
        assert json.loads(db_session.get(AgencyBudget, "068").by_year)[0]["fiscalYear"] == 2026
        assert db_session.get(AgencyBudget, "068").agency_slug == "environmental-protection-agency"
        assert len(quiet_alerts) == 2

    async def test_an_agency_slug_a_static_page_uses_is_alerted(self, db_session, quiet_alerts):
        listed = [*FR_LIST, {"id": 9, "slug": "budget", "name": "Budget", "parent_id": None}]
