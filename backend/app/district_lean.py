"""Civitas-computed district lean, shown beside Cook's PVI — never scored.

app/data/district_lean.json is generated by scripts/build_district_lean.py
from open precinct returns (VEST 2020, MEDSL 2024, Census blocks) with
Cook's formula, per Congress's district lines. Member scoring keeps
reading Cook's published values (district_pvi.json); this figure is for
readers to compare against, with its method and its validation against
Cook in the same file.

The file is bundled and only changes with a release (nothing rewrites it at
runtime), so it is read once per process.
"""

import functools
import json
import logging
import pathlib

logger = logging.getLogger(__name__)

PATH = pathlib.Path(__file__).resolve().parent / "data" / "district_lean.json"

# Where the reader-facing pages link for the method.
METHOD_HREF = "/about/data#computed-lean"


@functools.cache
def _file() -> dict:
    try:
        data = json.loads(PATH.read_text())
    except (OSError, ValueError):
        logger.error("district_lean.json unreadable: the computed lean is left out everywhere")
        return {}
    return data if isinstance(data, dict) else {}


def computed_lean(congress: int | None) -> dict[str, float]:
    """"ST-N" -> computed lean (positive = R) on that Congress's lines;
    empty for a Congress the file has no table for (the next cycle's
    lines before anyone has built them) — never another Congress's."""
    if congress is None:
        return {}
    table = ((_file().get("congresses") or {}).get(str(congress)) or {}).get("districts")
    return table if isinstance(table, dict) else {}


def lean_for(state: str, district: int | None, congress: int | None) -> float | None:
    return computed_lean(congress).get(f"{state}-{district if district is not None else 0}")


def meta() -> dict | None:
    """Provenance for a page that shows the figure: source, method,
    window, date, and the validation against Cook per Congress."""
    data = _file()
    if not data:
        return None
    return {
        "source": data.get("_source"),
        "method": data.get("_method"),
        "window": data.get("_window"),
        "asOf": data.get("_as_of"),
        "href": METHOD_HREF,
        "againstCook": (data.get("validation") or {}).get("againstCook"),
    }
