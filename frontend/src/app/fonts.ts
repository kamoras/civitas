type LoadedFont = { style: { fontFamily: string } };

/** Splits a next/font `fontFamily` value ("'a', 'a Fallback'") into its
 *  names. Family names never contain a comma. */
function families(font: LoadedFont): string[] {
  return font.style.fontFamily.split(",").map((name) => name.trim());
}

/** One family stack for a typeface split across subset calls: every
 *  subset's face, then their fallbacks, then any fallback named here. */
export function familyStack(faces: LoadedFont[], ...fallbacks: string[]): string {
  const names = faces.map(families);
  return [
    ...names.map(([face]) => face),
    ...names.flatMap(([, ...rest]) => rest),
    ...fallbacks,
  ].join(", ");
}

/** The family fonts/fallback.css declares. */
export const ARCHIVO_FALLBACK = "Archivo Fallback";

/** The two split typefaces' CSS variables, set on <body> where next/font
 *  would put a `variable` class (lib/shareImage.ts reads them there). */
export const fontVariables = {
  "--font-archivo": familyStack(
    [archivoLatin, archivoLatinExt, archivoVietnamese],
    `'${ARCHIVO_FALLBACK}'`
  ),
  "--font-press-start": familyStack([
    pressStartLatin,
    pressStartLatinExt,
    pressStartCyrillic,
    pressStartCyrillicExt,
    pressStartGreek,
  ]),
} as CSSProperties;
