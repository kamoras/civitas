/* The site's three typefaces, committed to the repo rather than fetched
   from Google Fonts while `next build` runs.

   next/font/google downloads fonts at build time, and about one build in
   five failed there: Google intermittently answers with a
   `fonts.gstatic.com/l/font?kit=…` URL that Turbopack's loader rejects
   ("queries have exactly one entry"). The files in ./fonts are the ones
   that loader downloaded — byte-for-byte, fetched with its User-Agent by
   backend/scripts/fetch_site_fonts.py, which also records Google's
   unicode-range for each file in ./fonts/manifest.json (fonts.test.ts
   holds this file to it). Rerun that script to update a face.

   Google splits each family into one file per script behind a
   unicode-range, so a page downloads only the scripts its text uses. That
   is kept: next/font/local applies one unicode-range per call, so each
   subset is its own call, and the CSS variable is assembled below with
   every subset face ahead of the fallback. Anywhere earlier, the fallback
   (a local() face with no unicode-range) would take every character the
   latin face lacks. Only the latin subsets are preloaded, as with
   next/font/google's `subsets: ["latin"]`.

   Under Turbopack the emitted font-family is the const's name
   (`archivoLatin`), so renaming a const renames the family; nothing
   outside this file names one. Options must be literals — next/font reads
   them at compile time — hence the repeated ranges. */

