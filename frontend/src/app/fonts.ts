/* The site's four typefaces, committed to the repo rather than fetched
   from Google Fonts while `next build` runs.

   next/font/google downloads fonts at build time, and about one build in
   five failed there: Google intermittently answers with a
   `fonts.gstatic.com/l/font?kit=…` URL that Turbopack's loader rejects
   ("queries have exactly one entry"). The files in ./fonts are the ones
   that loader downloaded, byte-for-byte, fetched with its User-Agent by
   backend/scripts/fetch_site_fonts.py, which also records Google's
   unicode-range for each file in ./fonts/manifest.json (fonts.test.ts
   holds this file to it). Rerun that script to update a face.

   The faces (2026-10, the register redesign), all SIL OFL 1.1:
     Source Serif 4 600  page and section titles (`font-display`)
     Fira Sans 400, 600 body, UI, labels and figures (`font-sans`, and
                         `font-mono` too: labels keep their class while
                         prose stops being set in a monospace)
     DM Mono 400         record identifiers only (`font-id`)
     Archivo 800         the wordmark (`font-wordmark`)
   Press Start 2P and Share Tech Mono are gone: mono for prose and a pixel
   face were most of what made the site read as a terminal.

   Google splits each family into one file per script (and, for a static
   family like Fira Sans, per weight) behind a unicode-range, so a page
   downloads only the scripts its text uses. next/font/local applies one
   unicode-range per call, so each file is its own call, and each CSS
   variable is assembled below with every face ahead of the fallback. Only
   the latin files are preloaded, as with next/font/google's
   `subsets: ["latin"]`.

   Every call turns next/font's generated fallback off; fonts/fallback.css
   holds metric-matched ones instead, generated by the same script from the
   capsize metrics next/font/google uses (DM Mono has none, so it falls back
   to the system monospace).

   Under Turbopack the emitted font-family is the const's name, so renaming
   a const renames the family; nothing outside this file names one. Options
   must be literals (next/font reads them at compile time), hence the
   repeated ranges. */

